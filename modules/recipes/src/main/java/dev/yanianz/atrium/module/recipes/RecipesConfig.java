package dev.yanianz.atrium.module.recipes;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.spongepowered.configurate.objectmapping.ConfigSerializable;
import org.spongepowered.configurate.objectmapping.meta.Comment;

/** plugins/Atrium/modules/recipes.yml. The recipe files live in plugins/Atrium/modules/recipes/. */
@ConfigSerializable
public class RecipesConfig {
    @Comment("Load and register the custom recipes from plugins/Atrium/modules/recipes/*.yml. One file is one\n"
            + "recipe and its file name is the id (registered as atrium:<id>). Keys: type (shaped, shapeless,\n"
            + "furnace, blasting, smoking, campfire, stonecutting, smithing), result {material, amount, name,\n"
            + "lore, custom-model-data, enchantments}, shaped {pattern, key}, shapeless {ingredients}, cooking\n"
            + "{input, experience, cooking-time}, stonecutting {input}, smithing {template, base, addition}.")
    public boolean customRecipes = true;

    @Comment("Discover all custom recipes in the recipe book of players with atrium.recipes.discover when\n"
            + "they join and after /customrecipe reload. Turning this off only hides them from the recipe book;\n"
            + "the recipes still work when a player knows the layout.")
    public boolean autoDiscover = true;

    @Comment("Enchantment limits enforced at every source: enchanting table, anvil, villager trades and loot.")
    public Enchantments enchantments = new Enchantments();

    @Comment("Anvil repair cost and rename rules.")
    public Anvil anvil = new Anvil();

    @ConfigSerializable
    public static class Enchantments {
        @Comment("Enforce the disabled list and maximum levels below.")
        public boolean enabled = true;

        @Comment("Enchantments that may never appear on an item. Plain names (sharpness) and namespaced names\n"
                + "(minecraft:sharpness) are both accepted.")
        public List<String> disabled = new ArrayList<>();

        @Comment("Maximum level per enchantment, for example sharpness: 3. An enchantment that is not listed\n"
                + "keeps its vanilla maximum.")
        public Map<String, Integer> maxLevels = new LinkedHashMap<>();

        @Comment("Apply the rules to enchanting table offers and to the enchantment that is actually applied.")
        public boolean enchantingTable = true;

        @Comment("Apply the rules to anvil results (levels are capped, disabled enchantments are stripped).")
        public boolean anvil = true;

        @Comment("Clear the anvil result instead of only stripping a disabled enchantment from it.\n"
                + "This is stricter and tells the player that the combination is not allowed.")
        public boolean anvilClearDisabled = false;

        @Comment("Strip disabled enchantments from villager trades and cap their levels.")
        public boolean villagerTrades = true;

        @Comment("Replace an enchanted book trade with a plain book when every stored enchantment was removed.")
        public boolean replaceEmptyBookTrades = true;

        @Comment("Cap or strip enchantments on items generated by loot tables.")
        public boolean loot = true;

        @Comment("Clean the player's inventory and ender chest on join. This removes forbidden enchantments\n"
                + "that were obtained before the rule was added. Only the player's own items are touched.")
        public boolean sanitizeOnJoin = true;
    }

    @ConfigSerializable
    public static class Anvil {
        @Comment("Let players with atrium.recipes.anvil.bypass use an anvil above the vanilla 40-level limit.")
        public boolean bypassRepairCost = true;

        @Comment("Highest repair cost the bypass allows (40-1000000); the current cost is always allowed too.")
        public int bypassMaxCost = 1000;

        @Comment("Also lift the vanilla anvil enchantment level restriction for the bypass permission.")
        public boolean bypassEnchantmentLevelLimit = true;

        @Comment("Allow colour tags in anvil renames (needs atrium.recipes.anvil.color).")
        public boolean coloredRenames = true;

        @Comment("Allow decoration tags such as <bold> in anvil renames (needs atrium.recipes.anvil.format).")
        public boolean decoratedRenames = true;

        @Comment("Maximum plain-text length of a formatted rename (1-256). Longer names stay plain.")
        public int maxRenameLength = 64;
    }
}
