package dev.yanianz.atrium.core.docs;

import com.mojang.brigadier.tree.ArgumentCommandNode;
import com.mojang.brigadier.tree.CommandNode;
import com.mojang.brigadier.tree.LiteralCommandNode;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.SortedMap;
import java.util.TreeMap;

/**
 * Renders the command and permission reference ({@code /atrium docs}) as Markdown. Pure: callers collect
 * the data, this class only formats it, so the output is deterministic and unit-testable.
 */
public final class DocsGenerator {
    /** Hard caps so a pathological command tree cannot produce a huge file. */
    static final int MAX_USAGES_PER_COMMAND = 40;
    static final int MAX_DEPTH = 12;

    public record CommandDoc(String owner, String name, List<String> aliases, String description,
            List<String> usages, boolean disabled) {}

    public record PermissionDoc(String node, String defaultValue, String description) {}

    private DocsGenerator() {}

    /**
     * Every executable path of a command as a usage line, e.g. {@code /home [name]} is reported as
     * {@code /home} and {@code /home <name>}. Literals are written as-is, arguments as {@code <name>}.
     */
    public static <S> List<String> usages(LiteralCommandNode<S> root) {
        return usages(root, node -> true);
    }

    /**
     * Like {@link #usages(LiteralCommandNode)} but skips every child node for which {@code visible} is false,
     * e.g. {@code node -> node.canUse(source)} lists only what a sender may run. The root itself is not
     * tested; check it before calling.
     */
    public static <S> List<String> usages(LiteralCommandNode<S> root, java.util.function.Predicate<? super CommandNode<S>> visible) {
        List<String> out = new ArrayList<>();
        walk(root, "/" + root.getLiteral(), 0, out, visible);
        return out;
    }

    private static <S> void walk(CommandNode<S> node, String prefix, int depth, List<String> out,
            java.util.function.Predicate<? super CommandNode<S>> visible) {
        if (out.size() >= MAX_USAGES_PER_COMMAND) {
            return;
        }
        if (node.getCommand() != null) {
            out.add(prefix);
        }
        if (depth >= MAX_DEPTH) {
            return;
        }
        if (node.getRedirect() != null) {
            out.add(prefix + " ...");
            return;
        }
        for (CommandNode<S> child : node.getChildren()) {
            if (!visible.test(child)) {
                continue;
            }
            String part = child instanceof ArgumentCommandNode<?, ?> arg ? "<" + arg.getName() + ">"
                    : child instanceof LiteralCommandNode<?> lit ? lit.getLiteral() : child.getName();
            walk(child, prefix + " " + part, depth + 1, out, visible);
        }
    }

    public static String commandsMarkdown(String version, Collection<CommandDoc> commands) {
        SortedMap<String, List<CommandDoc>> byOwner = new TreeMap<>();
        for (CommandDoc doc : commands) {
            byOwner.computeIfAbsent(doc.owner(), k -> new ArrayList<>()).add(doc);
        }
        StringBuilder md = new StringBuilder();
        md.append("# Atrium commands\n\n");
        md.append("Generated by `/atrium docs` for Atrium ").append(version).append(". ")
                .append(commands.size()).append(" commands in ").append(byOwner.size()).append(" modules.\n");
        md.append("Commands disabled in `config.yml` are marked ~~struck through~~.\n");
        for (Map.Entry<String, List<CommandDoc>> group : byOwner.entrySet()) {
            md.append("\n## ").append(group.getKey()).append("\n\n");
            md.append("| Command | Aliases | Description | Usage |\n|---|---|---|---|\n");
            List<CommandDoc> docs = new ArrayList<>(group.getValue());
            docs.sort((a, b) -> a.name().compareTo(b.name()));
            for (CommandDoc doc : docs) {
                String name = "`/" + doc.name() + "`";
                md.append("| ").append(doc.disabled() ? "~~" + name + "~~" : name)
                        .append(" | ").append(doc.aliases().isEmpty() ? "" : "`" + String.join("`, `", doc.aliases()) + "`")
                        .append(" | ").append(cell(doc.description()))
                        .append(" | ").append(doc.usages().isEmpty() ? "" : "`" + String.join("`<br>`", doc.usages().stream().map(DocsGenerator::code).toList()) + "`")
                        .append(" |\n");
            }
        }
        return md.toString();
    }

    public static String permissionsMarkdown(String version, SortedMap<String, ? extends Collection<PermissionDoc>> byModule) {
        int total = byModule.values().stream().mapToInt(Collection::size).sum();
        StringBuilder md = new StringBuilder();
        md.append("# Atrium permissions\n\n");
        md.append("Generated by `/atrium docs` for Atrium ").append(version).append(". ")
                .append(total).append(" permissions. Default: `true` = everyone, `op` = operators, `false` = nobody, ")
                .append("`not_op` = everyone except operators.\n");
        for (Map.Entry<String, ? extends Collection<PermissionDoc>> group : byModule.entrySet()) {
            if (group.getValue().isEmpty()) {
                continue;
            }
            md.append("\n## ").append(group.getKey()).append("\n\n| Permission | Default | Description |\n|---|---|---|\n");
            group.getValue().stream().sorted((a, b) -> a.node().compareTo(b.node())).forEach(doc ->
                    md.append("| `").append(code(doc.node())).append("` | ")
                            .append(doc.defaultValue().toLowerCase(Locale.ROOT)).append(" | ")
                            .append(cell(doc.description())).append(" |\n"));
        }
        return md.toString();
    }

    /** True when {@code name} or one of its aliases is in the disabled set (lower case). */
    public static boolean isDisabled(String name, Set<String> disabled) {
        return disabled.contains(name.toLowerCase(Locale.ROOT));
    }

    private static String cell(String text) {
        if (text == null) {
            return "";
        }
        return text.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ");
    }

    private static String code(String text) {
        return text.replace("`", "'").replace("|", "\\|");
    }
}
